def check_multicollinearity(df, variables):
    """Calculate VIF (Variance Inflation Factor) for multicollinearity"""
    
    X = df[variables].dropna()
    
    vif_data = pd.DataFrame()
    vif_data["Variable"] = variables
    vif_data["VIF"] = [variance_inflation_factor(X.values, i) for i in range(len(variables))]
    
    return vif_data.sort_values('VIF', ascending=False)


def fit_multiple_models(df):
    """Fit series of increasingly complex models"""
    
    y = df['DemocraticVoteShare'].values
    
    models = {}
    
    # Model 1: Education only (baseline)
    X1 = sm.add_constant(df[['BachelorsDegreeShare']])
    models['M1: Education Only'] = sm.OLS(y, X1).fit()
    
    # Model 2: Education + Urbanization
    X2 = sm.add_constant(df[['BachelorsDegreeShare', 'UrbanPercent']])
    models['M2: Education + Urban'] = sm.OLS(y, X2).fit()
    
    # Model 3: Education + Demographics
    X3 = sm.add_constant(df[['BachelorsDegreeShare', 'WhitePercent', 'MedianAge']])
    models['M3: Education + Demographics'] = sm.OLS(y, X3).fit()
    
    # Model 4: Education + Income (check multicollinearity!)
    X4 = sm.add_constant(df[['BachelorsDegreeShare', 'MedianIncome']])
    models['M4: Education + Income'] = sm.OLS(y, X4).fit()
    
    # Model 5: Full model without income (to avoid multicollinearity)
    X5 = sm.add_constant(df[['BachelorsDegreeShare', 'UrbanPercent', 'WhitePercent', 'MedianAge']])
    models['M5: Full (no income)'] = sm.OLS(y, X5).fit()
    
    # Model 6: Urbanization only (alternative hypothesis)
    X6 = sm.add_constant(df[['UrbanPercent']])
    models['M6: Urban Only'] = sm.OLS(y, X6).fit()
    
    # Model 7: With regional controls
    region_vars = [col for col in df.columns if col.startswith('Region_')]
    X7_cols = ['BachelorsDegreeShare', 'UrbanPercent'] + region_vars
    X7 = sm.add_constant(df[X7_cols].astype(float))
    models['M7: Education + Urban + Region'] = sm.OLS(y, X7).fit()
    
    return models


def create_model_comparison_table(models):
    """Create comparison table of model fit statistics"""
    
    comparison = []
    
    for name, model in models.items():
        comparison.append({
            'Model': name,
            'R²': f"{model.rsquared:.4f}",
            'Adj R²': f"{model.rsquared_adj:.4f}",
            'AIC': f"{model.aic:.2f}",
            'BIC': f"{model.bic:.2f}",
            'N Predictors': model.df_model
        })
    
    return pd.DataFrame(comparison)


