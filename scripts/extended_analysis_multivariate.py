def print_comprehensive_analysis(df, models, vif_data):
    """Print detailed analysis results"""
    
    print("="*80)
    print("EXTENDED MULTIVARIATE ANALYSIS")
    print("Alternative Explanations for 2024 Voting Patterns")
    print("="*80)
    
    print("\n" + "="*80)
    print("1. BIVARIATE CORRELATIONS WITH DEMOCRATIC VOTE SHARE")
    print("="*80)
    
    y = df['DemocraticVoteShare']
    variables = ['BachelorsDegreeShare', 'UrbanPercent', 'MedianIncome', 
                 'WhitePercent', 'MedianAge', 'PopDensity']
    
    corr_data = []
    for var in variables:
        r, p = stats.pearsonr(df[var], y)
        corr_data.append({
            'Variable': var,
            'Correlation': f"{r:.4f}",
            'p-value': f"{p:.2e}",
            'Significant': '***' if p < 0.001 else ('**' if p < 0.01 else ('*' if p < 0.05 else ''))
        })
    
    corr_df = pd.DataFrame(corr_data)
    corr_df = corr_df.sort_values('Correlation', ascending=False, key=lambda x: abs(x.str[1:].astype(float)))
    print("\n", corr_df.to_string(index=False))
    
    print("\n\n" + "="*80)
    print("2. MULTICOLLINEARITY CHECK (VIF)")
    print("="*80)
    print("\nVIF > 5 suggests problematic multicollinearity")
    print("VIF > 10 is severe multicollinearity\n")
    print(vif_data.to_string(index=False))
    
    print("\n\n" + "="*80)
    print("3. MODEL COMPARISON")
    print("="*80)
    
    comp_table = create_model_comparison_table(models)
    print("\n", comp_table.to_string(index=False))
    
    print("\n\n" + "="*80)
    print("4. DETAILED MODEL RESULTS")
    print("="*80)
    
    for name, model in models.items():
        print(f"\n{name}")
